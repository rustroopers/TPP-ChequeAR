#!/bin/bash
# Creación de usuarios HOSPITAL_MOCK y CHEQUEAR_RO usando passwords de env vars.
# Ejecutado por gvenzl/oracle-xe como SYS en /container-entrypoint-initdb.d.

set -euo pipefail

: "${HOSPITAL_MOCK_PASSWORD:?HOSPITAL_MOCK_PASSWORD no seteada}"
: "${CHEQUEAR_RO_PASSWORD:?CHEQUEAR_RO_PASSWORD no seteada}"

echo "[mock-hospital] Creando usuarios HOSPITAL_MOCK y CHEQUEAR_RO..."

sqlplus -S / AS SYSDBA <<SQL
ALTER SESSION SET CONTAINER = XEPDB1;

CREATE USER HOSPITAL_MOCK IDENTIFIED BY "${HOSPITAL_MOCK_PASSWORD}"
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, RESOURCE TO HOSPITAL_MOCK;
GRANT CREATE TABLE, CREATE VIEW TO HOSPITAL_MOCK;

CREATE USER CHEQUEAR_RO IDENTIFIED BY "${CHEQUEAR_RO_PASSWORD}";
GRANT CREATE SESSION TO CHEQUEAR_RO;

EXIT;
SQL

echo "[mock-hospital] Usuarios creados."
