-- =====================================================================
-- 01-schema.sql — Mock Hospital DB (PROVISIONAL)
-- =====================================================================
-- Crea los usuarios HOSPITAL_MOCK (owner) y CHEQUEAR_RO (consumidor),
-- más las tablas HOSP_* que el hospital expondrá vía vistas VW_*.
--
-- Ejecutado por el entrypoint de gvenzl/oracle-xe como SYS.
-- Las passwords se leen de variables de entorno definidas en docker-compose.
-- =====================================================================

ALTER SESSION SET CONTAINER = XEPDB1;

-- Los usuarios HOSPITAL_MOCK y CHEQUEAR_RO se crean en 00-users.sh
-- (las passwords vienen por env vars, sqlplus no las interpola por sí solo).

-- ----- Tablas internas HOSPITAL_MOCK.HOSP_* --------------------------

CREATE TABLE HOSPITAL_MOCK.HOSP_PACIENTE (
  ID_PACIENTE       VARCHAR2(16) NOT NULL,
  DOCUMENTO         VARCHAR2(15),
  TIPO_DOCUMENTO    VARCHAR2(8),
  NOMBRE            VARCHAR2(80) NOT NULL,
  APELLIDO          VARCHAR2(80) NOT NULL,
  FECHA_NACIMIENTO  DATE         NOT NULL,
  SEXO              VARCHAR2(1)  NOT NULL,
  COBERTURA         VARCHAR2(80),
  FECHA_ALTA_ADM    DATE         NOT NULL,
  ID_INTERNO        NUMBER(10)   NOT NULL,
  CONSTRAINT PK_HOSP_PACIENTE   PRIMARY KEY (ID_PACIENTE),
  CONSTRAINT UQ_HOSP_PAC_INT    UNIQUE (ID_INTERNO),
  CONSTRAINT CK_HOSP_PAC_SEXO   CHECK (SEXO IN ('M','F','O'))
);
CREATE INDEX IDX_HOSP_PAC_DOC ON HOSPITAL_MOCK.HOSP_PACIENTE (DOCUMENTO);

CREATE TABLE HOSPITAL_MOCK.HOSP_ESPECIALIDAD (
  COD_ESPECIALIDAD  VARCHAR2(8)   NOT NULL,
  NOMBRE            VARCHAR2(120) NOT NULL,
  CONSTRAINT PK_HOSP_ESPECIALIDAD PRIMARY KEY (COD_ESPECIALIDAD)
);

CREATE TABLE HOSPITAL_MOCK.HOSP_PROFESIONAL (
  ID_PROFESIONAL    VARCHAR2(16) NOT NULL,
  MATRICULA         VARCHAR2(20) NOT NULL,
  NOMBRE            VARCHAR2(80) NOT NULL,
  APELLIDO          VARCHAR2(80) NOT NULL,
  COD_ESPECIALIDAD  VARCHAR2(8)  NOT NULL,
  CONSTRAINT PK_HOSP_PROFESIONAL PRIMARY KEY (ID_PROFESIONAL),
  CONSTRAINT UQ_HOSP_PROF_MAT    UNIQUE (MATRICULA),
  CONSTRAINT FK_HOSP_PROF_ESP    FOREIGN KEY (COD_ESPECIALIDAD)
    REFERENCES HOSPITAL_MOCK.HOSP_ESPECIALIDAD (COD_ESPECIALIDAD)
);

CREATE TABLE HOSPITAL_MOCK.HOSP_EPISODIO (
  ID_EPISODIO            VARCHAR2(16)  NOT NULL,
  ID_PACIENTE            VARCHAR2(16)  NOT NULL,
  TIPO                   VARCHAR2(12)  NOT NULL,
  COD_ESPECIALIDAD       VARCHAR2(8)   NOT NULL,
  ID_PROFESIONAL_RESP    VARCHAR2(16)  NOT NULL,
  FECHA_INICIO           TIMESTAMP(0)  NOT NULL,
  FECHA_FIN              TIMESTAMP(0),
  MOTIVO_CONSULTA        VARCHAR2(400),
  CONSTRAINT PK_HOSP_EPISODIO  PRIMARY KEY (ID_EPISODIO),
  CONSTRAINT FK_HOSP_EPI_PAC   FOREIGN KEY (ID_PACIENTE)
    REFERENCES HOSPITAL_MOCK.HOSP_PACIENTE (ID_PACIENTE),
  CONSTRAINT FK_HOSP_EPI_ESP   FOREIGN KEY (COD_ESPECIALIDAD)
    REFERENCES HOSPITAL_MOCK.HOSP_ESPECIALIDAD (COD_ESPECIALIDAD),
  CONSTRAINT FK_HOSP_EPI_PROF  FOREIGN KEY (ID_PROFESIONAL_RESP)
    REFERENCES HOSPITAL_MOCK.HOSP_PROFESIONAL (ID_PROFESIONAL),
  CONSTRAINT CK_HOSP_EPI_TIPO  CHECK (TIPO IN ('AMBULATORIO','INTERNACION','URGENCIA')),
  CONSTRAINT CK_HOSP_EPI_FECHA CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);
CREATE INDEX IDX_HOSP_EPI_PAC ON HOSPITAL_MOCK.HOSP_EPISODIO (ID_PACIENTE, FECHA_INICIO DESC);

CREATE TABLE HOSPITAL_MOCK.HOSP_DIAGNOSTICO (
  ID_DIAGNOSTICO     NUMBER(10)   NOT NULL,
  ID_EPISODIO        VARCHAR2(16) NOT NULL,
  COD_CIE10          VARCHAR2(8)  NOT NULL,
  DISPLAY            VARCHAR2(200) NOT NULL,
  ES_PRINCIPAL       NUMBER(1)    NOT NULL,
  FECHA_DIAGNOSTICO  DATE         NOT NULL,
  CONSTRAINT PK_HOSP_DIAGNOSTICO PRIMARY KEY (ID_DIAGNOSTICO),
  CONSTRAINT FK_HOSP_DIAG_EPI    FOREIGN KEY (ID_EPISODIO)
    REFERENCES HOSPITAL_MOCK.HOSP_EPISODIO (ID_EPISODIO),
  CONSTRAINT CK_HOSP_DIAG_PRINC  CHECK (ES_PRINCIPAL IN (0,1))
);
CREATE INDEX IDX_HOSP_DIAG_EPI ON HOSPITAL_MOCK.HOSP_DIAGNOSTICO (ID_EPISODIO);
CREATE INDEX IDX_HOSP_DIAG_CIE ON HOSPITAL_MOCK.HOSP_DIAGNOSTICO (COD_CIE10);

CREATE TABLE HOSPITAL_MOCK.HOSP_OBSERVACION_LAB (
  ID_OBSERVACION    NUMBER(10)    NOT NULL,
  ID_EPISODIO       VARCHAR2(16)  NOT NULL,
  ID_PACIENTE       VARCHAR2(16)  NOT NULL,
  COD_LOINC         VARCHAR2(20)  NOT NULL,
  DISPLAY           VARCHAR2(200) NOT NULL,
  VALOR_NUMERICO    NUMBER(12,4),
  VALOR_TEXTO       VARCHAR2(120),
  UNIDAD            VARCHAR2(20),
  FECHA_TOMA        TIMESTAMP(0)  NOT NULL,
  CONSTRAINT PK_HOSP_OBSERVACION PRIMARY KEY (ID_OBSERVACION),
  CONSTRAINT FK_HOSP_OBS_EPI    FOREIGN KEY (ID_EPISODIO)
    REFERENCES HOSPITAL_MOCK.HOSP_EPISODIO (ID_EPISODIO),
  CONSTRAINT FK_HOSP_OBS_PAC    FOREIGN KEY (ID_PACIENTE)
    REFERENCES HOSPITAL_MOCK.HOSP_PACIENTE (ID_PACIENTE),
  CONSTRAINT CK_HOSP_OBS_VALOR  CHECK (VALOR_NUMERICO IS NOT NULL OR VALOR_TEXTO IS NOT NULL)
);
CREATE INDEX IDX_HOSP_OBS_PAC ON HOSPITAL_MOCK.HOSP_OBSERVACION_LAB (ID_PACIENTE, COD_LOINC, FECHA_TOMA DESC);

CREATE TABLE HOSPITAL_MOCK.HOSP_SIGNOS_VITALES (
  ID_SIGNO         NUMBER(10)    NOT NULL,
  ID_EPISODIO      VARCHAR2(16)  NOT NULL,
  FECHA_TOMA       TIMESTAMP(0)  NOT NULL,
  PESO_KG          NUMBER(5,2),
  TALLA_CM         NUMBER(5,1),
  FC_LPM           NUMBER(3),
  FR_RPM           NUMBER(3),
  TA_SISTOLICA     NUMBER(3),
  TA_DIASTOLICA    NUMBER(3),
  TEMPERATURA_C    NUMBER(3,1),
  CONSTRAINT PK_HOSP_SIGNOS    PRIMARY KEY (ID_SIGNO),
  CONSTRAINT FK_HOSP_SIG_EPI   FOREIGN KEY (ID_EPISODIO)
    REFERENCES HOSPITAL_MOCK.HOSP_EPISODIO (ID_EPISODIO)
);

CREATE TABLE HOSPITAL_MOCK.HOSP_MEDICACION (
  ID_MEDICACION     NUMBER(10)    NOT NULL,
  ID_EPISODIO       VARCHAR2(16)  NOT NULL,
  COD_ATC           VARCHAR2(10)  NOT NULL,
  NOMBRE_COMERCIAL  VARCHAR2(120) NOT NULL,
  DOSIS             VARCHAR2(60)  NOT NULL,
  VIA               VARCHAR2(20)  NOT NULL,
  FECHA_INICIO      DATE          NOT NULL,
  FECHA_FIN         DATE,
  CONSTRAINT PK_HOSP_MEDICACION PRIMARY KEY (ID_MEDICACION),
  CONSTRAINT FK_HOSP_MED_EPI    FOREIGN KEY (ID_EPISODIO)
    REFERENCES HOSPITAL_MOCK.HOSP_EPISODIO (ID_EPISODIO),
  CONSTRAINT CK_HOSP_MED_VIA    CHECK (VIA IN ('ORAL','IV','IM','TOPICA','INH'))
);

CREATE TABLE HOSPITAL_MOCK.HOSP_ALERGIA (
  ID_ALERGIA       NUMBER(10)    NOT NULL,
  ID_PACIENTE      VARCHAR2(16)  NOT NULL,
  SUSTANCIA        VARCHAR2(120),
  REACCION         VARCHAR2(200),
  SEVERIDAD        VARCHAR2(12),
  ESTADO           VARCHAR2(16)  NOT NULL,
  FECHA_REGISTRO   DATE          NOT NULL,
  CONSTRAINT PK_HOSP_ALERGIA   PRIMARY KEY (ID_ALERGIA),
  CONSTRAINT FK_HOSP_ALE_PAC   FOREIGN KEY (ID_PACIENTE)
    REFERENCES HOSPITAL_MOCK.HOSP_PACIENTE (ID_PACIENTE),
  CONSTRAINT CK_HOSP_ALE_EST   CHECK (ESTADO IN ('CONFIRMADA','SOSPECHADA','DESCONOCIDAS','DESCARTADA'))
);

CREATE TABLE HOSPITAL_MOCK.HOSP_TURNO (
  ID_TURNO         VARCHAR2(16)  NOT NULL,
  ID_PACIENTE      VARCHAR2(16)  NOT NULL,
  ID_PROFESIONAL   VARCHAR2(16)  NOT NULL,
  COD_ESPECIALIDAD VARCHAR2(8)   NOT NULL,
  FECHA_HORA       TIMESTAMP(0)  NOT NULL,
  ESTADO           VARCHAR2(12)  NOT NULL,
  CONSTRAINT PK_HOSP_TURNO    PRIMARY KEY (ID_TURNO),
  CONSTRAINT FK_HOSP_TUR_PAC  FOREIGN KEY (ID_PACIENTE)
    REFERENCES HOSPITAL_MOCK.HOSP_PACIENTE (ID_PACIENTE),
  CONSTRAINT FK_HOSP_TUR_PRO  FOREIGN KEY (ID_PROFESIONAL)
    REFERENCES HOSPITAL_MOCK.HOSP_PROFESIONAL (ID_PROFESIONAL),
  CONSTRAINT FK_HOSP_TUR_ESP  FOREIGN KEY (COD_ESPECIALIDAD)
    REFERENCES HOSPITAL_MOCK.HOSP_ESPECIALIDAD (COD_ESPECIALIDAD),
  CONSTRAINT CK_HOSP_TUR_EST  CHECK (ESTADO IN ('PROGRAMADO','ATENDIDO','AUSENTE','CANCELADO'))
);
