ALTER SESSION SET CONTAINER = XEPDB1;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_PACIENTE AS
SELECT
  ID_PACIENTE,
  DOCUMENTO,
  TIPO_DOCUMENTO,
  NOMBRE,
  APELLIDO,
  FECHA_NACIMIENTO,
  SEXO,
  COBERTURA
FROM HOSPITAL_MOCK.HOSP_PACIENTE;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_ESPECIALIDAD AS
SELECT
  COD_ESPECIALIDAD,
  NOMBRE
FROM HOSPITAL_MOCK.HOSP_ESPECIALIDAD;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_PROFESIONAL AS
SELECT
  P.ID_PROFESIONAL,
  P.MATRICULA,
  P.NOMBRE,
  P.APELLIDO,
  P.COD_ESPECIALIDAD,
  E.NOMBRE AS ESPECIALIDAD
FROM HOSPITAL_MOCK.HOSP_PROFESIONAL P
JOIN HOSPITAL_MOCK.HOSP_ESPECIALIDAD E
  ON E.COD_ESPECIALIDAD = P.COD_ESPECIALIDAD;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_EPISODIO AS
SELECT
  EP.ID_EPISODIO,
  EP.ID_PACIENTE,
  EP.TIPO,
  EP.COD_ESPECIALIDAD,
  ES.NOMBRE AS ESPECIALIDAD,
  EP.FECHA_INICIO,
  EP.FECHA_FIN,
  EP.MOTIVO_CONSULTA
FROM HOSPITAL_MOCK.HOSP_EPISODIO EP
JOIN HOSPITAL_MOCK.HOSP_ESPECIALIDAD ES
  ON ES.COD_ESPECIALIDAD = EP.COD_ESPECIALIDAD;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_DIAGNOSTICO AS
SELECT
  D.ID_DIAGNOSTICO,
  D.ID_EPISODIO,
  E.ID_PACIENTE,
  D.COD_CIE10,
  D.DISPLAY,
  D.ES_PRINCIPAL,
  D.FECHA_DIAGNOSTICO
FROM HOSPITAL_MOCK.HOSP_DIAGNOSTICO D
JOIN HOSPITAL_MOCK.HOSP_EPISODIO E
  ON E.ID_EPISODIO = D.ID_EPISODIO;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_OBSERVACION_LAB AS
SELECT
  ID_OBSERVACION,
  ID_PACIENTE,
  ID_EPISODIO,
  COD_LOINC,
  DISPLAY,
  VALOR_NUMERICO,
  VALOR_TEXTO,
  UNIDAD,
  FECHA_TOMA
FROM HOSPITAL_MOCK.HOSP_OBSERVACION_LAB;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_SIGNOS_VITALES AS
SELECT
  S.ID_SIGNO,
  S.ID_EPISODIO,
  E.ID_PACIENTE,
  S.FECHA_TOMA,
  S.PESO_KG,
  S.TALLA_CM,
  S.FC_LPM,
  S.FR_RPM,
  S.TA_SISTOLICA,
  S.TA_DIASTOLICA,
  S.TEMPERATURA_C
FROM HOSPITAL_MOCK.HOSP_SIGNOS_VITALES S
JOIN HOSPITAL_MOCK.HOSP_EPISODIO E
  ON E.ID_EPISODIO = S.ID_EPISODIO;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_MEDICACION AS
SELECT
  M.ID_MEDICACION,
  M.ID_EPISODIO,
  E.ID_PACIENTE,
  M.COD_ATC,
  M.NOMBRE_COMERCIAL,
  M.DOSIS,
  M.VIA,
  M.FECHA_INICIO,
  M.FECHA_FIN
FROM HOSPITAL_MOCK.HOSP_MEDICACION M
JOIN HOSPITAL_MOCK.HOSP_EPISODIO E
  ON E.ID_EPISODIO = M.ID_EPISODIO;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_ALERGIA AS
SELECT
  ID_ALERGIA,
  ID_PACIENTE,
  SUSTANCIA,
  REACCION,
  SEVERIDAD,
  ESTADO,
  FECHA_REGISTRO
FROM HOSPITAL_MOCK.HOSP_ALERGIA;

CREATE OR REPLACE VIEW HOSPITAL_MOCK.VW_TURNO AS
SELECT
  T.ID_TURNO,
  T.ID_PACIENTE,
  T.ID_PROFESIONAL,
  T.COD_ESPECIALIDAD,
  E.NOMBRE AS ESPECIALIDAD,
  T.FECHA_HORA,
  T.ESTADO
FROM HOSPITAL_MOCK.HOSP_TURNO T
JOIN HOSPITAL_MOCK.HOSP_ESPECIALIDAD E
  ON E.COD_ESPECIALIDAD = T.COD_ESPECIALIDAD;
